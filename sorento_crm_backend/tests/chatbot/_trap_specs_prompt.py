"""STOCK-QTY-PARTIAL-FILL: the TRAP SPECS and LIST FRAGMENT addenda, applied to the
production parser text.

Not itself a test file (no `test_` prefix). One applier
(`app.services.chatbot_parser_prompt.with_trap_specs`, the code fallback's own, run here
in strict mode), three readers: the static tests (`test_trap_specs_prompt_patch.py`), the
live-parser eval (`test_trap_specs_live_parser.py`) and the committed unified diff crew
sequences onto the live combined version (`alembic/data/chatbot_semantic_parser.trap-specs
.patch`, regenerated by `python -m tests.chatbot._trap_specs_prompt`). Same shape as
`_order_broaden_prompt.py`.

Two insertions, each at an anchor line that occurs exactly once in the production text:

* the TRAP SPECS rules go INSIDE the SPECIFICATIONS block, right after its last worked
  example (`SPEC_ANCHOR`), so the trap rule sits with the specification vocabulary it
  refines;
* the LIST FRAGMENT rule goes INSIDE "QUANTITIES and LAST_ANSWER", right before the bullet
  that says a product NOT on the list is a new question (`LIST_ANCHOR`), so the two readings
  of a code in the answer sit side by side.

The production file itself is never edited: `pdyn_0003` requires it to equal prod's live
text character for character.
"""
from __future__ import annotations

import difflib
import pathlib

from app.services import chatbot_parser_prompt as cpp

BACKEND = pathlib.Path(__file__).resolve().parents[2]
DATA = BACKEND / "alembic" / "data"
PROD = DATA / "chatbot_semantic_parser.prod-20261001.txt"
TRAP_ADDENDUM = DATA / "chatbot_semantic_parser.trap-specs.addendum.txt"
LIST_ADDENDUM = DATA / "chatbot_semantic_parser.list-fragment.addendum.txt"
PATCH = DATA / "chatbot_semantic_parser.trap-specs.patch"

SPEC_ANCHOR = cpp.TRAP_SPECS_ANCHOR
LIST_ANCHOR = cpp.LIST_FRAGMENT_ANCHOR


def prod_text() -> str:
    return PROD.read_text(encoding="utf-8")


def trap_addendum_text() -> str:
    return TRAP_ADDENDUM.read_text(encoding="utf-8")


def list_addendum_text() -> str:
    return LIST_ADDENDUM.read_text(encoding="utf-8")


def patched_text(text: str | None = None) -> str:
    """`text` (the production text by default) with both addenda inserted; each anchor
    must occur exactly once."""
    return cpp.with_trap_specs(prod_text() if text is None else text, strict=True)


def unified_patch() -> str:
    """The unified diff from the production file to the patched text, `patch -p0` shape
    against the file's path under `alembic/data`."""
    rel = PROD.relative_to(BACKEND).as_posix()
    before = prod_text().splitlines(keepends=True)
    after = patched_text().splitlines(keepends=True)
    return "".join(difflib.unified_diff(before, after, fromfile=rel, tofile=rel, n=3))


if __name__ == "__main__":
    PATCH.write_text(unified_patch(), encoding="utf-8")
    print(f"wrote {PATCH}")
