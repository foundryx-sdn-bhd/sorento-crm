"""ORDER-BROADEN: the BROADEN AXIS addendum, applied to the production parser text.

Not itself a test file (no `test_` prefix). One applier, three readers: the static
tests (`test_order_broaden_prompt_patch.py`), the live-parser journey
(`test_order_broaden_live_parser.py`) and the committed unified diff crew sequences onto
#1429's combined version (`alembic/data/chatbot_semantic_parser.order-broaden.patch`,
regenerated by `python -m tests.chatbot._order_broaden_prompt`).

The addendum goes INSIDE the "KEEP domain_hint and intent_hint" bullet of BROADEN AXIS,
right after its last line (`ANCHOR`, prod text line 507), so the miss example sits with
the rule it extends. The production file itself is never edited: `pdyn_0003` requires it
to equal prod's live text character for character.
"""
from __future__ import annotations

import difflib
import pathlib

BACKEND = pathlib.Path(__file__).resolve().parents[2]
DATA = BACKEND / "alembic" / "data"
PROD = DATA / "chatbot_semantic_parser.prod-20261001.txt"
ADDENDUM = DATA / "chatbot_semantic_parser.order-broaden.addendum.txt"
PATCH = DATA / "chatbot_semantic_parser.order-broaden.patch"

#: The last line of the KEEP bullet (prod text line 507). The addendum follows it.
ANCHOR = '    "catalogue", "spec of X") moves the domain to master_products.\n'


def prod_text() -> str:
    return PROD.read_text(encoding="utf-8")


def addendum_text() -> str:
    return ADDENDUM.read_text(encoding="utf-8")


def patched_text(text: str | None = None, addendum: str | None = None) -> str:
    """`text` with the addendum inserted after `ANCHOR`, which must occur exactly once."""
    text = prod_text() if text is None else text
    addendum = addendum_text() if addendum is None else addendum
    count = text.count(ANCHOR)
    if count != 1:
        raise ValueError(f"anchor line found {count} times, expected exactly once: {ANCHOR!r}")
    head, tail = text.split(ANCHOR)
    return head + ANCHOR + addendum + tail


def unified_patch() -> str:
    """The unified diff from the production file to the patched text, `patch -p0` shape
    against the file's path under `alembic/data`."""
    rel = PROD.relative_to(BACKEND).as_posix()
    before = prod_text().splitlines(keepends=True)
    after = patched_text().splitlines(keepends=True)
    return "".join(difflib.unified_diff(before, after, fromfile=rel, tofile=rel, n=3))


if __name__ == "__main__":
    PATCH.write_text(unified_patch(), encoding="utf-8")
    print(f"wrote {PATCH}")
